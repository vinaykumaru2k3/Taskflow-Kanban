/**
 * Custom Service Worker for TaskFlow
 * 
 * IMPORTANT: This file is used in development mode.
 * In production, vite-plugin-pwa generates the SW with proper Workbox integration.
 * 
 * This custom SW provides:
 * - Manual skipWaiting (controlled by the app via messages)
 * - Immediate client claiming
 * - Outdated cache cleanup
 */

importScripts('https://storage.googleapis.com/workbox-cdn/releases/7.0.0/workbox-sw.js');

const CACHE_NAME = 'taskflow-v1';
const RUNTIME_CACHE = 'taskflow-runtime-v1';

// Workbox modules
const { precacheAndRoute, cleanupOutdatedCaches } = workbox.precaching;
const { registerRoute } = workbox.routing;
const { CacheFirst, NetworkFirst, StaleWhileRevalidate } = workbox.strategies;
const { ExpirationPlugin } = workbox.expiration;
const { CacheableResponsePlugin } = workbox.cacheableResponse;

// Precache all assets generated by Vite (handled by plugin in production)
precacheAndRoute(self.__WB_MANIFEST);

// Clean up outdated caches
cleanupOutdatedCaches();

// ── Install: Skip waiting immediately (for first install)
// This ensures fresh install gets control right away
self.addEventListener('install', (event) => {
  console.log('[SW] Install event - skipping waiting');
  self.skipWaiting();
});

// ── Activate: Claim all clients immediately and clean up old caches ──
self.addEventListener('activate', (event) => {
  console.log('[SW] Activate event - claiming clients');
  
  // Combine both operations into a single Promise.all to avoid race condition
  // Only the last event.waitUntil is considered per SW spec
  event.waitUntil(Promise.all([
    // Claim all clients immediately so the new SW controls all pages
    self.clients.claim(),
    // Clean up old caches that don't match current version
    caches.keys().then((cacheNames) => {
      return Promise.all(
        cacheNames
          .filter((name) => {
            // Keep only current cache names
            const isCurrentCache = name === CACHE_NAME || name === RUNTIME_CACHE;
            const isPrecache = name.startsWith('precache-');
            return !isCurrentCache && !isPrecache;
          })
          .map((name) => {
            console.log('[SW] Deleting old cache:', name);
            return caches.delete(name);
          })
      );
    })
  ]));
});

// ── Message: Handle SKIP_WAITING from client ──
// This is triggered when the user clicks "Update" in the PWA banner
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    console.log('[SW] Received SKIP_WAITING message - activating new SW');
    self.skipWaiting();
  }
});

// ── Fetch: NetworkFirst for navigation requests (HTML) ──
registerRoute(
  ({ request }) => request.mode === 'navigate',
  new NetworkFirst({
    cacheName: CACHE_NAME,
    plugins: [
      new CacheableResponsePlugin({ statuses: [0, 200] }),
      new ExpirationPlugin({
        maxEntries: 50,
        maxAgeSeconds: 24 * 60 * 60, // 24 hours
      }),
    ],
  })
);

// ── Cache: Google Fonts (CacheFirst for performance) ──
registerRoute(
  ({ url }) => url.origin === 'https://fonts.googleapis.com',
  new CacheFirst({
    cacheName: 'google-fonts-cache',
    plugins: [
      new CacheableResponsePlugin({ statuses: [0, 200] }),
      new ExpirationPlugin({
        maxEntries: 10,
        maxAgeSeconds: 60 * 60 * 24 * 365, // 1 year
      }),
    ],
  })
);

registerRoute(
  ({ url }) => url.origin === 'https://fonts.gstatic.com',
  new CacheFirst({
    cacheName: 'gstatic-fonts-cache',
    plugins: [
      new CacheableResponsePlugin({ statuses: [0, 200] }),
      new ExpirationPlugin({
        maxEntries: 10,
        maxAgeSeconds: 60 * 60 * 24 * 365, // 1 year
      }),
    ],
  })
);

// ── Cache: Avatar images (StaleWhileRevalidate) ──
registerRoute(
  ({ url }) => url.origin === 'https://i.pravatar.cc',
  new StaleWhileRevalidate({
    cacheName: 'avatar-cache',
    plugins: [
      new CacheableResponsePlugin({ statuses: [0, 200] }),
      new ExpirationPlugin({
        maxEntries: 50,
        maxAgeSeconds: 60 * 60 * 24 * 7, // 1 week
      }),
    ],
  })
);

// ── Cache: Firebase Firestore (NetworkFirst for fresh data) ──
registerRoute(
  ({ url }) => url.origin === 'https://firestore.googleapis.com',
  new NetworkFirst({
    cacheName: 'firestore-cache',
    networkTimeoutSeconds: 5,
    plugins: [
      new CacheableResponsePlugin({ statuses: [0, 200] }),
      new ExpirationPlugin({
        maxEntries: 50,
        maxAgeSeconds: 60 * 5, // 5 minutes
      }),
    ],
  })
);

// ── Cache: Firebase Auth (NetworkFirst) ──
registerRoute(
  ({ url }) => url.origin === 'https://www.googleapis.com' && url.pathname.includes('identitytoolkit'),
  new NetworkFirst({
    cacheName: 'firebase-auth-cache',
    networkTimeoutSeconds: 5,
    plugins: [
      new CacheableResponsePlugin({ statuses: [0, 200] }),
      new ExpirationPlugin({
        maxEntries: 10,
        maxAgeSeconds: 60 * 5, // 5 minutes
      }),
    ],
  })
);

console.log('[SW] Service Worker loaded');

